import { Channel, Playlist } from '../types/iptv';

export function parseM3U(content: string, playlistName: string = 'Нова листа'): Playlist {
  const lines = content.replace(/\r\n/g, '\n').split('\n');
  const channels: Channel[] = [];

  let currentChannel: Partial<Channel> | null = null;
  let lineIndex = 0;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i].trim();
    if (!rawLine) continue;

    if (rawLine.startsWith('#EXTINF:')) {
      lineIndex++;
      currentChannel = {
        id: `ch_${Date.now()}_${lineIndex}_${Math.random().toString(36).substring(2, 7)}`,
        name: `Канал ${lineIndex}`,
        url: '',
        logo: '',
        group: 'Общи',
        status: 'untested',
      };

      // Extract attributes using regex
      const tvgIdMatch = rawLine.match(/tvg-id="([^"]*)"/i);
      if (tvgIdMatch) currentChannel.tvgId = tvgIdMatch[1];

      const tvgNameMatch = rawLine.match(/tvg-name="([^"]*)"/i);
      if (tvgNameMatch) currentChannel.tvgName = tvgNameMatch[1];

      const tvgLogoMatch = rawLine.match(/tvg-logo="([^"]*)"/i);
      if (tvgLogoMatch) currentChannel.logo = tvgLogoMatch[1];

      const groupMatch = rawLine.match(/group-title="([^"]*)"/i);
      if (groupMatch) currentChannel.group = groupMatch[1];

      const userAgentMatch = rawLine.match(/http-user-agent="([^"]*)"/i);
      if (userAgentMatch) currentChannel.httpUserAgent = userAgentMatch[1];

      const referrerMatch = rawLine.match(/http-referrer="([^"]*)"/i);
      if (referrerMatch) currentChannel.httpReferrer = referrerMatch[1];

      // Channel title after the comma
      const commaIndex = rawLine.lastIndexOf(',');
      if (commaIndex !== -1 && commaIndex < rawLine.length - 1) {
        const title = rawLine.substring(commaIndex + 1).trim();
        if (title) {
          currentChannel.name = title;
        }
      } else if (currentChannel.tvgName) {
        currentChannel.name = currentChannel.tvgName;
      }
    } else if (rawLine.startsWith('#EXTGRP:') && currentChannel) {
      currentChannel.group = rawLine.substring(8).trim() || currentChannel.group;
    } else if (rawLine.startsWith('#EXTVLCOPT:http-user-agent=') && currentChannel) {
      currentChannel.httpUserAgent = rawLine.substring(27).trim();
    } else if (rawLine.startsWith('#EXTVLCOPT:http-referrer=') && currentChannel) {
      currentChannel.httpReferrer = rawLine.substring(25).trim();
    } else if (!rawLine.startsWith('#')) {
      // It's a URL
      if (currentChannel) {
        currentChannel.url = rawLine;
        channels.push(currentChannel as Channel);
        currentChannel = null;
      } else if (rawLine.startsWith('http://') || rawLine.startsWith('https://')) {
        // Raw URL without #EXTINF
        lineIndex++;
        channels.push({
          id: `ch_${Date.now()}_${lineIndex}_${Math.random().toString(36).substring(2, 7)}`,
          name: `Стрийм ${lineIndex}`,
          url: rawLine,
          logo: '',
          group: 'Без категория',
          status: 'untested',
        });
      }
    }
  }

  return {
    id: `pl_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
    name: playlistName,
    channels,
    createdAt: Date.now(),
    updatedAt: Date.now(),
    source: 'custom',
  };
}

export function generateM3U(channels: Channel[], playlistTitle: string = 'IPTV ERD Playlist'): string {
  let output = '#EXTM3U\n';
  output += `## Playlist: ${playlistTitle}\n`;
  output += `## Generated by IPTV ERD Editor & VLC Player on ${new Date().toISOString()}\n\n`;

  for (const ch of channels) {
    const parts: string[] = ['#EXTINF:-1'];
    if (ch.tvgId) parts.push(`tvg-id="${ch.tvgId}"`);
    if (ch.tvgName) parts.push(`tvg-name="${ch.tvgName}"`);
    if (ch.logo) parts.push(`tvg-logo="${ch.logo}"`);
    if (ch.group) parts.push(`group-title="${ch.group}"`);
    if (ch.httpUserAgent) parts.push(`http-user-agent="${ch.httpUserAgent}"`);
    if (ch.httpReferrer) parts.push(`http-referrer="${ch.httpReferrer}"`);

    const extinfLine = `${parts.join(' ')},${ch.name}`;
    output += `${extinfLine}\n`;

    if (ch.httpUserAgent) {
      output += `#EXTVLCOPT:http-user-agent=${ch.httpUserAgent}\n`;
    }
    if (ch.httpReferrer) {
      output += `#EXTVLCOPT:http-referrer=${ch.httpReferrer}\n`;
    }

    output += `${ch.url}\n\n`;
  }

  return output;
}

export function downloadM3UFile(
  channels: Channel[],
  filename: string = 'playlist',
  format: 'm3u' | 'm3u8' = 'm3u'
) {
  const cleanName = filename.replace(/\.(m3u|m3u8)$/i, '');
  const content = generateM3U(channels, cleanName);
  const mimeType = format === 'm3u8' ? 'application/x-mpegurl;charset=utf-8' : 'audio/x-mpegurl;charset=utf-8';
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${cleanName}.${format}`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadM3U(channels: Channel[], filename: string = 'playlist') {
  downloadM3UFile(channels, filename, 'm3u');
}

export function downloadM3U8(channels: Channel[], filename: string = 'playlist') {
  downloadM3UFile(channels, filename, 'm3u8');
}

